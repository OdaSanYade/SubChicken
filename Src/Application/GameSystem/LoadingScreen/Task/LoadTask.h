#pragma once

// ----------------------------------------------------------
// ロードタスク1件
//
// 単発タスク  : func だけを設定する
// 分割タスク  : prepare / slot を設定する
//               prepare がスロット数を返し、slot が1件ずつ処理する
//
// commit は必ずメインスレッドで、prepare / slot の後に呼ばれる
// ----------------------------------------------------------
struct LoadTask
{
	// 表示名(ロード画面の左に出る)
	const char* label = "";

	// 実行段。小さい段が全て終わってから次の段へ進む
	int stage = 0;

	// --- 単発タスク ---
	// メインスレッドで1回だけ呼ばれる
	std::function<void()> func;

	// --- 分割タスク ---
	// スロット数を返す。0ならスロット処理をスキップ
	std::function<size_t()> prepare;

	// スロット1件を処理する。並列化後はワーカーから呼ばれる
	std::function<bool(size_t)> slot;

	// --- 後処理 ---
	// メインスレッドで1回だけ呼ばれる。省略可
	std::function<void()> commit;

	// 進捗の重み。分割タスクはスロット数で自動的に細かくなるので
	// ここは単発タスク同士のバランス調整に使う
	float weight = 1.0f;
};